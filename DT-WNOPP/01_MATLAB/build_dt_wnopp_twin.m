
function build_dt_wnopp_twin()
% BUILD_DT_WNOPP_TWIN
% Creates a system-level Simulink prototype.
%
% Inputs:
%   traffic_load     - normalised offered traffic [0,1]
%   resource_fraction - normalised resource allocation [0,1]
%
% Outputs are initial model proxies, not calibrated real-world values.

mdl = 'DT_WNOPP_Twin';
modelFile = fullfile(fileparts(mfilename('fullpath')), ...
    '..', '06_SIMULINK', [mdl '.slx']);

modelFile = char(java.io.File(modelFile).getCanonicalPath());

if bdIsLoaded(mdl)
    close_system(mdl, 0);
end

if exist(modelFile, 'file')
    delete(modelFile);
end

new_system(mdl);

set_param(mdl, ...
    'SolverType', 'Fixed-step', ...
    'Solver', 'FixedStepDiscrete', ...
    'FixedStep', '1', ...
    'StopTime', '999');

% Inputs
add_block('simulink/Sources/From Workspace', ...
    [mdl '/TrafficLoad'], ...
    'VariableName', 'traffic_ts', ...
    'Position', [40 70 160 100]);

add_block('simulink/Sources/From Workspace', ...
    [mdl '/ResourceFraction'], ...
    'VariableName', 'resource_ts', ...
    'Position', [40 190 160 220]);

% Protect the model from a zero resource allocation.
add_block('simulink/Discontinuities/Saturation', ...
    [mdl '/ResourceLimit'], ...
    'LowerLimit', '0.1', ...
    'UpperLimit', '1', ...
    'Position', [220 190 270 220]);

% Latency proxy: 15 + 100 * load^2 / resource_fraction
add_block('simulink/Math Operations/Math Function', ...
    [mdl '/SquareLoad'], ...
    'Operator', 'square', ...
    'Position', [220 60 270 100]);

add_block('simulink/Math Operations/Math Function', ...
    [mdl '/ReciprocalResource'], ...
    'Operator', 'reciprocal', ...
    'Position', [320 190 370 230]);

add_block('simulink/Math Operations/Product', ...
    [mdl '/LoadResourceProduct'], ...
    'Position', [420 75 460 125]);

add_block('simulink/Math Operations/Gain', ...
    [mdl '/LatencyScale'], ...
    'Gain', '100', ...
    'Position', [510 75 570 115]);

add_block('simulink/Sources/Constant', ...
    [mdl '/BaseLatency'], ...
    'Value', '15', ...
    'Position', [510 145 570 175]);

add_block('simulink/Math Operations/Sum', ...
    [mdl '/LatencyProxy'], ...
    'Inputs', '++', ...
    'Position', [620 80 650 130]);

add_block('simulink/Sinks/To Workspace', ...
    [mdl '/SaveLatency'], ...
    'VariableName', 'latency_proxy_ms', ...
    'SaveFormat', 'Timeseries', ...
    'Position', [710 85 820 115]);

% Throughput proxy: load * resource_fraction
add_block('simulink/Math Operations/Product', ...
    [mdl '/ThroughputProxy'], ...
    'Position', [320 300 370 340]);

add_block('simulink/Sinks/To Workspace', ...
    [mdl '/SaveThroughput'], ...
    'VariableName', 'throughput_proxy', ...
    'SaveFormat', 'Timeseries', ...
    'Position', [450 305 560 335]);

% Packet-loss proxy: 0.1 + 4 * max(load - 0.65, 0)
add_block('simulink/Sources/Constant', ...
    [mdl '/LossThreshold'], ...
    'Value', '0.65', ...
    'Position', [220 410 270 440]);

add_block('simulink/Math Operations/Sum', ...
    [mdl '/LoadMinusThreshold'], ...
    'Inputs', '+-', ...
    'Position', [320 390 350 430]);

add_block('simulink/Discontinuities/Saturation', ...
    [mdl '/PositiveExcess'], ...
    'LowerLimit', '0', ...
    'UpperLimit', '1', ...
    'Position', [390 390 440 430]);

add_block('simulink/Math Operations/Gain', ...
    [mdl '/LossScale'], ...
    'Gain', '4', ...
    'Position', [480 390 530 430]);

add_block('simulink/Sources/Constant', ...
    [mdl '/BaseLoss'], ...
    'Value', '0.1', ...
    'Position', [480 455 530 485]);

add_block('simulink/Math Operations/Sum', ...
    [mdl '/LossProxy'], ...
    'Inputs', '++', ...
    'Position', [580 390 610 440]);

add_block('simulink/Sinks/To Workspace', ...
    [mdl '/SavePacketLoss'], ...
    'VariableName', 'packet_loss_proxy_pct', ...
    'SaveFormat', 'Timeseries', ...
    'Position', [680 395 810 425]);

% Connections
add_line(mdl, 'TrafficLoad/1', 'SquareLoad/1');
add_line(mdl, 'ResourceFraction/1', 'ResourceLimit/1');
add_line(mdl, 'ResourceLimit/1', 'ReciprocalResource/1');

add_line(mdl, 'SquareLoad/1', 'LoadResourceProduct/1');
add_line(mdl, 'ReciprocalResource/1', 'LoadResourceProduct/2');
add_line(mdl, 'LoadResourceProduct/1', 'LatencyScale/1');
add_line(mdl, 'LatencyScale/1', 'LatencyProxy/1');
add_line(mdl, 'BaseLatency/1', 'LatencyProxy/2');
add_line(mdl, 'LatencyProxy/1', 'SaveLatency/1');

add_line(mdl, 'TrafficLoad/1', 'ThroughputProxy/1');
add_line(mdl, 'ResourceLimit/1', 'ThroughputProxy/2');
add_line(mdl, 'ThroughputProxy/1', 'SaveThroughput/1');

add_line(mdl, 'TrafficLoad/1', 'LoadMinusThreshold/1');
add_line(mdl, 'LossThreshold/1', 'LoadMinusThreshold/2');
add_line(mdl, 'LoadMinusThreshold/1', 'PositiveExcess/1');
add_line(mdl, 'PositiveExcess/1', 'LossScale/1');
add_line(mdl, 'LossScale/1', 'LossProxy/1');
add_line(mdl, 'BaseLoss/1', 'LossProxy/2');
add_line(mdl, 'LossProxy/1', 'SavePacketLoss/1');

save_system(mdl, modelFile);
open_system(mdl);

fprintf('Created Simulink model: %s\n', modelFile);
end
